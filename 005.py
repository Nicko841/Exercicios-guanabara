#Faça um programa que leia um número Inteiro e mostre na tela o seu sucessor e seu antecessor.

numerolegal = int(input('Digite um número: '))
sucessor = numerolegal + 1
antecessor = numerolegal - 1
print('Numero escolhido: {}'.format(numerolegal))
print('Sucessor do numero: {}'.format(sucessor))
print('Antecessor do número: {}'.format(antecessor))
